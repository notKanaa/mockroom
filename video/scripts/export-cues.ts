// Writes the film's sound cues to audio-cues.json, in both languages, with times
// in seconds and a brief per sound: the list to make the final sounds from (for
// instance with ElevenLabs), and to check them against in an audio editor.
// A final sound goes in public/audio/final/<sound>.wav (or .mp3) and replaces its sketch.
//
//   npm run cues

import { writeFileSync } from "node:fs";
import { locales } from "../src/content/locales";
import { FILM_FRAMES, filmCues, parts, soundBriefs } from "../src/v2/cues";

const FPS = 30;
const seconds = (frames: number) => Math.round((frames / FPS) * 1000) / 1000;

const cuesFor = (locale: "en" | "fr") =>
  filmCues(locales[locale].sample).map((cue) => ({
    sound: cue.sound,
    seconds: seconds(cue.frame),
    ...(cue.until !== undefined && { fadesOutAt: seconds(cue.until) }),
    volume: Math.round(cue.volume * 100) / 100,
    ...(cue.rate !== undefined && { rate: cue.rate }),
  }));

const en = cuesFor("en");
const used = [...new Set(en.map((cue) => cue.sound))].sort();
let start = 0;
const output = {
  note: "Generated by `npm run cues` from src/v2/cues.ts. Edit the cues there, not here.",
  fps: FPS,
  durationSeconds: seconds(FILM_FRAMES),
  parts: parts(locales.en.sample).map((part) => {
    const entry = { id: part.id, startSeconds: seconds(start), durationSeconds: seconds(part.frames) };
    start += part.frames;
    return entry;
  }),
  sounds: used.map((sound) => ({
    sound,
    replaceWith: `public/audio/final/${sound}.wav`,
    brief: soundBriefs[sound] ?? "",
    uses: en.filter((cue) => cue.sound === sound).length,
  })),
  cues: { en, fr: cuesFor("fr") },
};

writeFileSync("audio-cues.json", `${JSON.stringify(output, null, 2)}\n`);
console.log(`audio-cues.json: ${used.length} sounds, ${en.length} cues, ${output.durationSeconds} s`);
