// Writes the audio cues (src/audio/cues.ts) to audio-cues.json, with their times in
// seconds, for both languages: the list to generate the sounds from, and to check
// them against in an audio editor.
//
//   npm run cues

import { writeFileSync } from "node:fs";
import { promoCues, resolveCues } from "../src/audio/cues";
import { FPS, PROMO_FRAMES, scenes, sceneStart } from "../src/timeline";

const cue = (locale: "en" | "fr") =>
  resolveCues(promoCues(locale)).map(({ id, kind, scene, seconds, lengthSeconds, file, volume, description }) => ({
    id,
    kind,
    scene,
    seconds,
    ...(lengthSeconds !== undefined && { lengthSeconds }),
    file,
    volume,
    description,
  }));

const output = {
  note: "Generated by `npm run cues` from src/audio/cues.ts. Edit the cues there, not here.",
  fps: FPS,
  durationSeconds: PROMO_FRAMES / FPS,
  scenes: scenes.map((scene) => ({
    id: scene.id,
    startSeconds: sceneStart(scene.id) / FPS,
    durationSeconds: scene.duration / FPS,
  })),
  cues: { en: cue("en"), fr: cue("fr") },
};

writeFileSync("audio-cues.json", `${JSON.stringify(output, null, 2)}\n`);
console.log(`audio-cues.json: ${output.cues.en.length} cues per language, ${output.durationSeconds} s`);
